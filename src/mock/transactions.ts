export const getTransactionsByUser = (userId: string, role: string) => {
  if (role === 'provider' || role === 'admin') {
    return mockTransactions.filter((t) => t.sellerId === userId || role === 'admin');
  }
  return mockTransactions.filter((t) => t.buyerId === userId);
};
